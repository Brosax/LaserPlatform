class LanguageManager(QtCore.QObject):
    """Singleton-style language manager that emits signal on language change."""

    language_changed = QtCore.Signal(str)  # emits lang code "en"/"zh"/"es"

    LANGUAGES = {"en": "English", "zh": "中文", "es": "Español"}
    _current = "en"

    def set_language(self, lang: str):
        if lang in self.LANGUAGES and lang != self._current:
            self._current = lang
            self.language_changed.emit(lang)

    def current(self) -> str:
        return self._current


_manager = LanguageManager()


def language_manager() -> LanguageManager:
    return _manager


def tr(key: str) -> str:
    """Translate key to current language, falling back to English."""
    return _TRANSLATIONS.get(_manager.current(), {}).get(
        key, _TRANSLATIONS["en"].get(key, key)
    )
